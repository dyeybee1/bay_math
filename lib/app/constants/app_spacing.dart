/// Centralized spacing scale, based on a 4px unit.
///
/// Use these everywhere padding, margin, or gap values are needed instead
/// of writing literal numbers — keeps spacing visually consistent across
/// every screen and component.
class AppSpacing {
  const AppSpacing._();

  static const double xs = 4;
  static const double sm = 8;
  static const double md = 16;
  static const double lg = 24;
  static const double xl = 32;
  static const double xxl = 48;
}
